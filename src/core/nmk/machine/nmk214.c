static const uint8_t output_byte_bitswaps[8][8] =
{
//   D0   D1   D2   D3   D4   D5   D6   D7
	{0x4, 0x1, 0x3, 0x5, 0x6, 0x0, 0x7, 0x2},  // byte bitswap 0
	{0x6, 0x4, 0x1, 0x5, 0x2, 0x7, 0x0, 0x3},  // byte bitswap 1
	{0x2, 0x3, 0x4, 0x1, 0x0, 0x5, 0x6, 0x7},  // byte bitswap 2
	{0x1, 0x5, 0x0, 0x2, 0x6, 0x7, 0x4, 0x3},  // byte bitswap 3
	{0x7, 0x3, 0x0, 0x4, 0x5, 0x6, 0x2, 0x1},  // byte bitswap 4
	{0x0, 0x1, 0x2, 0x3, 0x4, 0x5, 0x6, 0x7},  // byte bitswap 5
	{0x6, 0x7, 0x5, 0x3, 0x4, 0x1, 0x0, 0x2},  // byte bitswap 6
	{0x1, 0x2, 0x6, 0x4, 0x0, 0x7, 0x3, 0x5}   // byte bitswap 7
};

static uint8_t select_value(const nmk214_t *n, uint32_t addr)
{
	uint32_t eff = 0;
	for (int i = 0; i < 13; i++)
		eff |= ((addr >> n->addr_bitswap[i]) & 1) << i;
	uint32_t sel = 0;
	for (int i = 0; i < 3; i++)
		sel |= ((eff >> selection_address_bits[n->init_config][i]) & 1) << i;
	uint8_t r = 0;
	for (int j = 0; j < 3; j++)
		r |= (uint8_t)(((init_configs[n->init_config][j] >> sel) & 1) << j);
	return r;
}

uint16_t nmk214_decode_word(const nmk214_t *n, uint32_t addr, uint16_t data)
{
	const uint8_t *t = output_word_bitswaps[select_value(n, addr)];
	uint16_t r = 0;
	for (int i = 0; i < 16; i++)
		r |= (uint16_t)(((data >> t[i]) & 1) << i);
	return r;
}

uint8_t nmk214_decode_byte(const nmk214_t *n, uint32_t addr, uint8_t data)
{
	const uint8_t *t = output_byte_bitswaps[select_value(n, addr)];
	uint8_t r = 0;
	for (int i = 0; i < 8; i++)
		r |= (uint8_t)(((data >> t[i]) & 1) << i);
	return r;
}

void nmk214_set_init_config(nmk214_t *n, uint8_t init_config)
{
	if (((init_config >> 3) & 1) == n->mode) {
		n->init_config = init_config & 7;
		n->initialized = 1;
	}
}
