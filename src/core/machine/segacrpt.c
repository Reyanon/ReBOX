// segacrpt_device.cpp decode() (without banks)
static void decode1(uint8_t *data, uint8_t *opcodes, int size, const uint8_t convtable[32][4])
{
	for (int A = 0x0000; A < size; A++) {
		int xorval = 0;
		const uint8_t src = data[A];
		// pick the translation table from bits 0, 4, 8 and 12 of the address
		const int row = (A & 1) + (((A >> 4) & 1) << 1) + (((A >> 8) & 1) << 2) + (((A >> 12) & 1) << 3);
		// pick the offset in the table from bits 3 and 5 of the source data
		int col = ((src >> 3) & 1) + (((src >> 5) & 1) << 1);
		// the bottom half of the translation table is the mirror image of the top
		if (src & 0x80) {
			col = 3 - col;
			xorval = 0xa8;
		}
		opcodes[A] = (uint8_t)((src & ~0xa8) | (convtable[2 * row][col] ^ xorval));
		data[A] = (uint8_t)((src & ~0xa8) | (convtable[2 * row + 1][col] ^ xorval));
		if (convtable[2 * row][col] == 0xff)   // (table incomplete)
			opcodes[A] = 0xee;
		if (convtable[2 * row + 1][col] == 0xff)
			data[A] = 0xee;
	}
}

#define BIT(x, n) (((x) >> (n)) & 1)

// segacrp2_device.cpp decode()
static void decode2(uint8_t *rom, uint8_t *decrypted, const uint8_t *xor_table, const uint8_t *swap_table)
{
	static const uint8_t swaptable[24][4] = {
		{ 6,4,2,0 }, { 4,6,2,0 }, { 2,4,6,0 }, { 0,4,2,6 },
		{ 6,2,4,0 }, { 6,0,2,4 }, { 6,4,0,2 }, { 2,6,4,0 },
		{ 4,2,6,0 }, { 4,6,0,2 }, { 6,0,4,2 }, { 0,6,4,2 },
		{ 4,0,6,2 }, { 0,4,6,2 }, { 6,2,0,4 }, { 2,6,0,4 },
		{ 0,6,2,4 }, { 2,0,6,4 }, { 0,2,6,4 }, { 4,2,0,6 },
		{ 2,4,0,6 }, { 4,0,2,6 }, { 2,0,4,6 }, { 0,2,4,6 } };
	for (int a = 0x0000; a < 0x8000; a++) {
		const uint8_t src = rom[a];
		// pick the translation table from bits 0, 3, 6, 9, 12 and 14 of the address
		const int row = BIT(a, 14) << 5 | BIT(a, 12) << 4 | BIT(a, 9) << 3 | BIT(a, 6) << 2 | BIT(a, 3) << 1 | BIT(a, 0);
		for (int k = 0; k < 2; k++) {   // the opcodes, then the data (bitswap<8>(src, 7, t0, 5, t1, 3, t2, 1, t3))
			const uint8_t *tbl = swaptable[swap_table[2 * row + k]];
			const uint8_t v = (uint8_t)(BIT(src, 7) << 7 | BIT(src, tbl[0]) << 6 | BIT(src, 5) << 5 | BIT(src, tbl[1]) << 4 |
			                            BIT(src, 3) << 3 | BIT(src, tbl[2]) << 2 | BIT(src, 1) << 1 | BIT(src, tbl[3]));
			if (k == 0)
				decrypted[a] = (uint8_t)(v ^ xor_table[2 * row]);
			else
				rom[a] = (uint8_t)(v ^ xor_table[2 * row + 1]);
		}
	}
}

