#define BIT(x, n) (((x) >> (n)) & 1)
static inline uint32_t bitswap(uint32_t v, int n, const int *b)   // MAME bitswap<n>: b[0] the source of the top bit
{
	uint32_t r = 0;
	for (int i = 0; i < n; i++)
		r |= (uint32_t)BIT(v, b[i]) << (n - 1 - i);
	return r;
}
#define BS(n, v, ...) bitswap((uint32_t)(v), n, (const int[]){ __VA_ARGS__ })

