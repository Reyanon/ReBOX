// ---- PVC: the P ROMs, the cartridge RAM (colours packed / unpacked, the bank) ----
// (the bytes are MAME's on a little-endian host: BYTE_XOR_LE(i) = i)
static void pvc_swap16(uint8_t *rom, uint32_t from, uint32_t to, const int *b)
{
	for (uint32_t i = from; i < to; i += 4) {
		uint16_t rom16 = (uint16_t)(rom[i + 1] | rom[i + 2] << 8);
		rom16 = (uint16_t)bitswap(rom16, 16, b);
		rom[i + 1] = (uint8_t)rom16;
		rom[i + 2] = (uint8_t)(rom16 >> 8);
	}
}
static int pvc_decrypt_8m(uint8_t *rom, const uint8_t *xor1, const uint8_t *xor2, const int *swap16, const int *b1,
                          int x1, const int *b2)   // mslug5, svc
{
	const int rom_size = 0x800000;
	uint8_t *buf = (uint8_t *)malloc((size_t)rom_size);
	if (!buf)
		return -1;
	for (int i = 0; i < 0x100000; i++)
		rom[i] ^= xor1[i % 0x20];
	for (int i = 0x100000; i < 0x800000; i++)
		rom[i] ^= xor2[i % 0x20];
	pvc_swap16(rom, 0x100000, 0x800000, swap16);
	memcpy(buf, rom, (size_t)rom_size);
	for (int i = 0; i < 0x0100000 / 0x10000; i++) {
		const int ofst = (i & 0xf0) + (int)bitswap((uint32_t)(i & 0x0f), 8, b1);
		memcpy(&rom[i * 0x10000], &buf[ofst * 0x10000], 0x10000);
	}
	for (int i = 0x100000; i < 0x800000; i += 0x100) {
		const int ofst = (i & 0xf000ff) + ((i & 0x000f00) ^ x1) + ((int)bitswap((uint32_t)((i & 0x0ff000) >> 12), 8, b2) << 12);
		memcpy(&rom[i], &buf[ofst], 0x100);
	}
	memcpy(buf, rom, (size_t)rom_size);
	memcpy(&rom[0x100000], &buf[0x700000], 0x100000);
	memcpy(&rom[0x200000], &buf[0x100000], 0x600000);
	free(buf);
	return 0;
}
