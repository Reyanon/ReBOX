static void pvc_write_unpack_color(uint16_t *ram)
{
	const uint16_t pen = ram[0xff0];
	const uint8_t b = (uint8_t)(((pen & 0x000f) << 1) | ((pen & 0x1000) >> 12));
	const uint8_t g = (uint8_t)(((pen & 0x00f0) >> 3) | ((pen & 0x2000) >> 13));
	const uint8_t r = (uint8_t)(((pen & 0x0f00) >> 7) | ((pen & 0x4000) >> 14));
	const uint8_t s = (uint8_t)((pen & 0x8000) >> 15);
	ram[0xff1] = (uint16_t)((g << 8) | b);
	ram[0xff2] = (uint16_t)((s << 8) | r);
}
static void pvc_write_pack_color(uint16_t *ram)
{
	const uint16_t gb = ram[0xff4], sr = ram[0xff5];
	ram[0xff6] = (uint16_t)(((gb & 0x001e) >> 1) | ((gb & 0x1e00) >> 5) | ((sr & 0x001e) << 7) | ((gb & 0x0001) << 12) |
	                        ((gb & 0x0100) << 5) | ((sr & 0x0001) << 14) | ((sr & 0x0100) << 7));
}
void neo_pvc_w(uint16_t *ram, int offset, uint16_t data, uint16_t mask)
{
	ram[offset] = (uint16_t)((data & mask) | (ram[offset] & ~mask));
	if (offset == 0xff0)
		pvc_write_unpack_color(ram);
	else if (offset >= 0xff4 && offset <= 0xff5)
		pvc_write_pack_color(ram);
}
uint32_t neo_pvc_bank_base(uint16_t *ram)
{
	const uint32_t bankaddress = (uint32_t)((ram[0xff8] >> 8) | (ram[0xff9] << 8));
	ram[0xff8] = (uint16_t)((ram[0xff8] & 0xfe00) | 0x00a0);
	ram[0xff9] &= 0x7fff;
	return bankaddress + 0x100000;
}

// ---- KOF98: the P ROM, the overlay at 0x100 ----
int neo_kof98_decrypt_68k(uint8_t *cpurom, uint32_t cpurom_size, uint16_t *default_rom)
{
	static const uint32_t sec[] = { 0x000000, 0x100000, 0x000004, 0x100004, 0x10000a, 0x00000a, 0x10000e, 0x00000e };
	static const uint32_t pos[] = { 0x000, 0x004, 0x00a, 0x00e };
	uint8_t *src = cpurom;
	if (cpurom_size < 0x600000)
		return -1;
	uint8_t *dst = (uint8_t *)malloc(0x200000);
	if (!dst)
		return -1;
	memcpy(dst, src, 0x200000);
	for (int i = 0x800; i < 0x100000; i += 0x200) {
		for (int j = 0; j < 0x100; j += 0x10) {
			for (int k = 0; k < 16; k += 2) {
				memcpy(&src[i + j + k], &dst[i + j + sec[k / 2] + 0x100], 2);
				memcpy(&src[i + j + k + 0x100], &dst[i + j + sec[k / 2]], 2);
			}
			if (i >= 0x080000 && i < 0x0c0000) {
				for (int k = 0; k < 4; k++) {
					memcpy(&src[i + j + pos[k]], &dst[i + j + pos[k]], 2);
					memcpy(&src[i + j + pos[k] + 0x100], &dst[i + j + pos[k] + 0x100], 2);
				}
			} else if (i >= 0x0c0000) {
				for (int k = 0; k < 4; k++) {
					memcpy(&src[i + j + pos[k]], &dst[i + j + pos[k] + 0x100], 2);
					memcpy(&src[i + j + pos[k] + 0x100], &dst[i + j + pos[k]], 2);
				}
			}
		}
		memcpy(&src[i + 0x000000], &dst[i + 0x000000], 2);
		memcpy(&src[i + 0x000002], &dst[i + 0x100000], 2);
		memcpy(&src[i + 0x000100], &dst[i + 0x000100], 2);
		memcpy(&src[i + 0x000102], &dst[i + 0x100100], 2);
	}
	memmove(&src[0x100000], &src[0x200000], 0x400000);
	free(dst);
	const uint16_t *mem16 = (const uint16_t *)cpurom;
	default_rom[0] = mem16[0x100 / 2];
	default_rom[1] = mem16[0x102 / 2];
	return 0;
}

// ---- Metal Slug X ----
void neo_mslugx_w(neo_mslugx_t *p, int offset, uint16_t data)
{
	switch (offset) {
	case 0x0 / 2: p->command = 0; break;
	case 0x2 / 2: case 0x4 / 2: p->command |= data; break;
	case 0xa / 2: p->counter = 0; p->command = 0; break;
	default: break;
	}
}
uint16_t neo_mslugx_r(neo_mslugx_t *p, uint8_t (*read_byte)(uint32_t), uint16_t (*read_word)(uint32_t))
{
	uint16_t res = 0;
	switch (p->command) {
	case 0x0001:
		res = (uint16_t)((read_byte(0xdedd2 + ((p->counter >> 3) & 0xfff)) >> (~p->counter & 7)) & 1);
		p->counter++;
		break;
	case 0x0fff: {
		const int32_t select = (int32_t)read_word(0x10f00a) - 1;
		res = (uint16_t)((read_byte(0xdedd2 + (uint32_t)((select >> 3) & 0x0fff)) >> (~select & 7)) & 1);
		break;
	}
	default: break;
	}
	return res;
}

// ---- Fatal Fury 2: the PRO-CT0 (alpha_8921) ----
static void ct0_update(neo_proct0_t *c)
{
	if (c->old_sr != c->sr || c->old_even != c->even || c->old_h != c->h) {
		if (c->h) {
			c->gbd = (uint8_t)BS(4, c->sr, 30, 22, 14, 6);
			c->gad = (uint8_t)BS(4, c->sr, 31, 23, 15, 7);
		} else {
			c->gbd = (uint8_t)BS(4, c->sr, 25, 17, 9, 1);
			c->gad = (uint8_t)BS(4, c->sr, 24, 16, 8, 0);
		}
		if (c->even) {
			const uint8_t t = c->gad;
			c->gad = c->gbd;
			c->gbd = t;
		}
		c->old_sr = c->sr;
		c->old_even = c->even;
		c->old_h = c->h;
	}
}
static void ct0_clk(neo_proct0_t *c, int state)
{
	if (c->clk != state) {
		c->clk = (uint8_t)state;
		if (!c->clk) {
			const uint32_t sr = c->sr;
			if (c->load)
				c->sr = c->c;
			else if (c->h)
				c->sr = (((sr >> 24) & 0x3f) << 26) | (((sr >> 16) & 0x3f) << 18) | (((sr >> 8) & 0x3f) << 10) | ((sr & 0x3f) << 2);
			else
				c->sr = (((sr >> 26) & 0x3f) << 24) | (((sr >> 18) & 0x3f) << 16) | (((sr >> 10) & 0x3f) << 8) | ((sr >> 2) & 0x3f);
		}
	}
}
void neo_proct0_reset(neo_proct0_t *c)
{
	c->old_sr = ~c->sr;
	c->old_even = (uint8_t)!c->even;
	c->old_h = (uint8_t)!c->h;
	ct0_update(c);
}
uint16_t neo_fatfury2_r(neo_proct0_t *c, uint32_t offset)
{
	c->even = (uint8_t)BIT(offset, 1);
	c->h = (uint8_t)BIT(offset, 2);
	ct0_update(c);
	const uint8_t gad = c->gad & 15, gbd = c->gbd & 15;
	return (uint16_t)((((gbd >> 0) & 3) << 6) | (((gbd >> 2) & 3) << 4) | (((gad >> 0) & 3) << 2) | ((gad >> 2) & 3));
}
void neo_fatfury2_w(neo_proct0_t *c, uint32_t offset, uint16_t data)
{
	ct0_clk(c, 1);
	c->load = (uint8_t)BIT(offset, 0);
	c->even = (uint8_t)BIT(offset, 1);
	c->h = (uint8_t)BIT(offset, 2);
	c->c = (BS(16, (offset >> 3) & 0xffff, 15, 11, 14, 10, 13, 9, 12, 8, 7, 3, 6, 2, 5, 1, 4, 0) << 16) |
	       BS(16, data, 15, 11, 14, 10, 13, 9, 12, 8, 7, 3, 6, 2, 5, 1, 4, 0);
	ct0_clk(c, 0);
}
