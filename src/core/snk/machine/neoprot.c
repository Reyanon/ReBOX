void neo_sfix_decrypt(const uint8_t *rom, uint32_t rom_size, uint8_t *fixed, uint32_t fixed_size)
{
	const uint8_t *src = rom + rom_size - fixed_size;
	for (uint32_t i = 0; i < fixed_size; i++)
		fixed[i] = src[(i & ~0x1fu) + ((i & 7) << 2) + ((~i & 8) >> 2) + ((i & 0x10) >> 4)];
}

static int m1_address_scramble(int address, uint16_t key)
{
	static const int p1[8][16] = {
		{15,14,10,7,1,2,3,8,0,12,11,13,6,9,5,4},
		{7,1,8,11,15,9,2,3,5,13,4,14,10,0,6,12},
		{8,6,14,3,10,7,15,1,4,0,2,5,13,11,12,9},
		{2,8,15,9,3,4,11,7,13,6,0,10,1,12,14,5},
		{1,13,6,15,14,3,8,10,9,4,7,12,5,2,0,11},
		{11,15,3,4,7,0,9,2,6,14,12,1,8,5,10,13},
		{10,5,13,8,6,15,1,14,11,9,3,0,12,7,4,2},
		{9,3,7,0,2,12,4,11,14,10,5,8,15,13,1,6},
	};
	const int block = (address >> 16) & 7;
	int aux = address & 0xffff;
	aux ^= (int)BS(16, key, 12,0,2,4,8,15,7,13,10,1,3,6,11,9,14,5);
	int perm[16];   // (bitswap<16>(aux, p1[block][15] .. p1[block][0]))
	for (int i = 0; i < 16; i++)
		perm[i] = p1[block][15 - i];
	aux = (int)bitswap((uint32_t)aux, 16, perm);
	aux ^= m1_address_0_7_xor[(aux >> 8) & 0xff];
	aux ^= m1_address_8_15_xor[aux & 0xff] << 8;
	aux = (int)BS(16, aux, 7,15,14,6,5,13,12,4,11,3,10,2,9,1,8,0);
	return (block << 16) | aux;
}

int neo_cmc50_m1_decrypt(uint8_t *romcrypt, uint32_t romcrypt_size, uint8_t *romaudio, uint32_t romaudio_size)
{
	const uint32_t rom_size = 0x80000;
	if (romcrypt_size < rom_size || romaudio_size < 0x90000)
		return -1;
	uint8_t *buffer = (uint8_t *)malloc(rom_size);
	if (!buffer)
		return -1;
	uint16_t key = 0;   // (util::sum16_creator::simple: the bytes of the first 64 KB summed)
	for (uint32_t i = 0; i < 0x10000; i++)
		key = (uint16_t)(key + romcrypt[i]);
	for (uint32_t i = 0; i < rom_size; i++)
		buffer[i] = romcrypt[m1_address_scramble((int)i, key)];
	memcpy(romcrypt, buffer, rom_size);
	memcpy(romaudio, romcrypt, 0x10000);
	memcpy(romaudio + 0x10000, romcrypt, 0x80000);
	free(buffer);
	return 0;
}

// ---- SMA: the P ROMs' data and address lines, the bank numbers, the random numbers ----
uint16_t neo_sma_random(uint16_t *rng)
{
	const uint16_t old = *rng;
	const uint16_t newbit = (uint16_t)(((*rng >> 2) ^ (*rng >> 3) ^ (*rng >> 5) ^ (*rng >> 6) ^ (*rng >> 7) ^ (*rng >> 11) ^
	                                    (*rng >> 12) ^ (*rng >> 15)) & 1);
	*rng = (uint16_t)((*rng << 1) | newbit);
	return old;
}

